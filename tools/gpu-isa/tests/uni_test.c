static f32b gmem[64];
static uint32_t rdmem(void * ctx, uint64_t va) { (void)ctx; return gmem[(va - 0x100000) / 4]; }

static int run(const char * name, const uint8_t * prog, unsigned len, unsigned entry, uint32_t vid, const float * want, void (*setup)(struct s8f_ctx *))
{
	struct s8f_ctx c;
	unsigned st = s8v_find_start(prog, len, entry);
	int bad = 0;

	memset(&c, 0, sizeof(c));
	c.rd = rdmem;
	c.vid = vid;
	setup(&c);
	int ok = s8f_run(&c, prog + st, len - st);
	printf("%s vid %u: start %u ok=%d unknown=0x%02x stride=%u\n", name, vid, st, ok, c.unknown, c.stride);
	for (int i = 0; i < 8; i++) {
		if (!(c.expmask & (1u << i)) || tof(c.exp[i]) != want[i]) {
			printf("  slot 0x%02x: got %g (%s) want %g\n", 0x40 + i, tof(c.exp[i]), (c.expmask >> i) & 1 ? "exported" : "NOT exported", want[i]);
			bad++;
		}
	}
	return bad;
}

static void setupA(struct s8f_ctx * c)
{
	c->uni[0] = 0x100000; c->uni[2] = 0;                    /* vertex buffer pointer */
	c->uni[8] = tob(0.5f); c->uni[10] = tob(0.75f); c->uni[12] = tob(1.7f); c->uni[14] = tob(2.9f);
}
static void setupD(struct s8f_ctx * c)
{
	c->uni[0] = 0x100000; c->uni[2] = 0;
	c->uni[12] = tob(0.3f); c->uni[14] = tob(0.6f); c->uni[16] = tob(0.125f); c->uni[18] = tob(-0.25f);   /* v at half 0xc */
	c->uni[20] = tob(0.5f); c->uni[22] = tob(0.75f);                                                   /* u.xy at half 0x14 */
}
static void setupC(struct s8f_ctx * c) { c->uni[0] = 0x100000; c->uni[2] = 0; }

int main(void)
{
	int bad = 0;
	/* 16-byte vertices (x, y, z, w) for xA, vid 0 and 2 */
	float vb[3][4] = { { -0.5f, -0.5f, 0.25f, 0.5f }, { 0.5f, -0.5f, 0.75f, 0.125f }, { 0.0f, 0.5f, 0.375f, 0.625f } };
	/* 32-byte interleaved vertices (pos x y z w, col r g b a) for xC */
	float iv[3][8] = { { -0.5f, -0.5f, 0.0f, 1.0f, 0.9f, 0.1f, 0.2f, 1.0f }, { 0.5f, -0.5f, 0.0f, 1.0f, 0.1f, 0.9f, 0.2f, 1.0f },
	                   { 0.0f, 0.5f, 0.0f, 1.0f, 0.1f, 0.2f, 0.9f, 1.0f } };
	float wantA0[8] = { -0.5f * 0.5f, -0.5f * 0.75f, 0.0f, 1.0f, 0.5f, 0.75f, 1.7f, 2.9f };
	float wantA2[8] = { 0.0f, 0.5f * 0.75f, 0.0f, 1.0f, 0.5f, 0.75f, 1.7f, 2.9f };
	float wantC1[8] = { 0.5f, -0.5f, 0.0f, 1.0f, 0.1f, 0.9f, 0.2f, 1.0f };

	memset(gmem, 0, sizeof(gmem));
	for (int i = 0; i < 3; i++) for (int k = 0; k < 4; k++) gmem[i * 4 + k] = tob(vb[i][k]);
	bad += run("xA", xA, sizeof(xA), 20, 0, wantA0, setupA);
	bad += run("xA", xA, sizeof(xA), 20, 2, wantA2, setupA);
	memset(gmem, 0, sizeof(gmem));
	for (int i = 0; i < 3; i++) for (int k = 0; k < 8; k++) gmem[i * 8 + k] = tob(iv[i][k]);
	bad += run("xC", xC, sizeof(xC), 20, 1, wantC1, setupC);
	{
		float wantD1[8] = { 0.5f * 0.5f + 0.125f, -0.5f * 0.75f + -0.25f, 0.0f, 1.0f, 0.3f, 0.6f, 0.125f, -0.25f };

		memset(gmem, 0, sizeof(gmem));
		for (int i2 = 0; i2 < 3; i2++) for (int k = 0; k < 4; k++) gmem[i2 * 4 + k] = tob(vb[i2][k]);
		bad += run("xD", xD, sizeof(xD), 20, 1, wantD1, setupD);
	}
	printf("%s\n", bad ? "FAIL" : "uniform-file vertex stage reproduces xA and xC");
	return bad != 0;
}
