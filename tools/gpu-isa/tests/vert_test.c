static int check(const char * name, const uint8_t * img, unsigned len, unsigned ptr, int nfetch, const float * want)
{
	f32b vtx[4] = { tob(-0.5f), tob(0.25f), tob(0.75f), tob(0.125f) };
	struct s8f_ctx c;
	unsigned st = s8v_find_start(img, len, ptr);
	int bad = 0;

	memset(&c, 0, sizeof(c));
	c.fetch = vtx;
	c.nfetch = nfetch;
	int ok = s8f_run(&c, img + st, len - st);
	printf("%s: start offset %u (entry %u) ok=%d unknown=0x%02x\n", name, st, ptr, ok, c.unknown);
	for (int i = 0; i < 8; i++) {
		if (!(c.expmask & (1u << i)) || tof(c.exp[i]) != want[i]) {
			printf("  slot 0x%02x: got %g (%s) want %g\n", 0x40 + i, tof(c.exp[i]), (c.expmask >> i) & 1 ? "exported" : "NOT exported", want[i]);
			bad++;
		}
	}
	return bad;
}

int main(void)
{
	/* wB: pos = (vb.xyz, 1.0), col = (0.3, 0.6, 0.9, 0.2) */
	float wantB[8] = { -0.5f, 0.25f, 0.75f, 1.0f, tof(0x3e99999a), tof(0x3f19999a), tof(0x3f666666), tof(0x3e4ccccd) };
	/* wD: pos = (vb.xy, 0, 1), col = 0 */
	float wantD[8] = { -0.5f, 0.25f, 0.0f, 1.0f, 0, 0, 0, 0 };
	int bad = 0;

	bad += check("wB", wB, sizeof(wB), 4 + 12 + 2 /* inside the third mov_imm */, 4, wantB);
	bad += check("wD", wD, sizeof(wD), 22 + 12 /* entry inside the prologue, as on the phone */, 4, wantD);
	{
		/* vF: col = vb * 2 (2.0 immediate), pos = (x, y, 0, 1); the fetched vertex is (-0.5, 0.25, 0.75, 0.125) */
		float wantF[8] = { -0.5f, 0.25f, 0.0f, 1.0f, -1.0f, 0.5f, 1.5f, 0.25f };

		bad += check("vF", wF, sizeof(wF), 0, 4, wantF);
	}
	printf("%s\n", bad ? "FAIL" : "vertex stage reproduces the captured programs");
	return bad != 0;
}
