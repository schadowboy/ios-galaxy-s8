#!/usr/bin/env python3
"""Make the function table of eagl_s8.c: one function of ours for every entry of the table that Darwin's
OpenGLES hands out through -[EAGLContext getMacroContextPrivate] (eagl_slots.txt).

  mkeagl_s8.py SLOTS GL.XML EAGL.C > eagl_gen_s8.h

Adapted from userland/mkeagl.py of the S9+ port (MIT, Copyright (c) 2025-2026 the HakiOS authors; full text in
userland/s8mali/s8mali_drm.h). Differences:
  - the OpenGL ES library is NOT linked: it is dlopen()ed at run time (libOSMesa.8.dylib of userland/mesa), so
    there is no list of exported functions. Every gl* function the generated code or eagl_s8.c calls is a
    static function POINTER of that name (`static GLenum (*glGetError)(void);`), filled by eagl_resolve_functions()
    from hook_gl_proc(); a name the library does not have stays NULL and the entry says so once
    ("CALLED AND NOT THERE") instead of failing to load.
  - the generated file is committed (eagl_gen_s8.h): neither CI nor a Mac needs gl.xml. Regenerate with
    userland/hook/mkeagl_s8.py after changing eagl_slots.txt or the my_gl* functions of eagl_s8.c.

GL.XML is the Khronos registry (https://github.com/KhronosGroup/OpenGL-Registry, xml/gl.xml); it gives the
prototypes. EAGL.C is searched for the functions written by hand (static ... my_glName(void *context, ...)),
which take the place of the generated ones.

An entry is called as entry(table[0], arguments...). What is generated for it:
  - a function that counts the call and passes the arguments on to the library's function of that name
    (the first name of the slot's list that gl.xml knows; at run time the name, else the name without its
    OES/EXT/APPLE/ARB/IMG ending);
  - where gl.xml knows none of the names (OpenGL ES 1, Apple's own), a function that says once which entry
    was called and returns 0;
  - the same for the offsets between the known entries.
The header is in two parts: with EAGL_GEN_DECLARATIONS defined, the pointers and the resolver; with
EAGL_GEN_TABLE, the functions and eagl_fill_table().
"""
import re
import sys
import xml.etree.ElementTree as ET

slots_path, xml_path, source_path = sys.argv[1:4]

slots = []                                      # (offset, used by QuartzCore, [names])
for line in open(slots_path):
    line = line.split('#')[0].split()
    if line:
        slots.append((int(line[0], 16), line[1] == '*', line[2:]))

protos = {}                                     # name -> (return type, [(type, name)])
for command in ET.parse(xml_path).getroot().iter('command'):
    proto = command.find('proto')
    if proto is None:
        continue
    name = proto.find('name').text
    ret = ''.join(proto.itertext())
    ret = ret[:ret.rindex(name)].strip()
    params = []
    for param in command.findall('param'):
        text = ''.join(param.itertext()).strip()
        pname = param.find('name').text
        params.append((text[:text.rindex(pname)].strip(), pname))
    protos[name] = (ret, params)

source = open(source_path).read()
by_hand = set(re.findall(r'^my_(gl\w+)\(', source, re.M))


def trace_format(ctype):
    if '*' in ctype or ctype in ('GLsync', 'GLeglImageOES', 'GLDEBUGPROC', 'GLDEBUGPROCKHR'):
        return '%p'
    if ctype in ('GLenum', 'GLbitfield'):
        return '%#x'
    if ctype in ('GLfloat', 'GLclampf', 'GLdouble', 'GLclampd'):
        return '%g'
    if ctype in ('GLintptr', 'GLsizeiptr'):
        return '%ld'
    if ctype in ('GLuint64', 'GLint64'):
        return '%lld'
    return '%d'


def trace_value(param):
    ctype, name = param
    if '*' in ctype or ctype in ('GLsync', 'GLeglImageOES', 'GLDEBUGPROC', 'GLDEBUGPROCKHR'):
        return '(const void *)%s' % name
    if ctype in ('GLfloat', 'GLclampf', 'GLdouble', 'GLclampd'):
        return '(double)%s' % name
    if ctype in ('GLuint64', 'GLint64'):
        return '(long long)%s' % name
    return name


out = []
emit = out.append
emit('/* Generated by userland/hook/mkeagl_s8.py from eagl_slots.txt and the Khronos gl.xml; not to be edited. */')
emit('#ifdef EAGL_GEN_DECLARATIONS')
needed = {}
entries = []                                    # (offset, name, kind, function)
for offset, used, names in slots:
    hand = [n for n in names if n in by_hand]
    if hand:
        entries.append((offset, names[0], 'hand', 'my_' + hand[0]))
        continue
    choice = None
    for n in names:
        if n in protos:
            choice = n
            break
    if choice is None:
        entries.append((offset, names[0], 'none', None))
    else:
        entries.append((offset, choice, 'pass', choice))
        needed[choice] = protos[choice]
# ... and what the functions written by hand call
for name in set(re.findall(r'(?<![\w])(gl[A-Z]\w*)\s*\(', source)):
    if name in protos:
        needed.setdefault(name, protos[name])
for name in sorted(needed):
    ret, params = needed[name]
    emit('static %s (*%s)(%s);' % (ret, name, ', '.join('%s %s' % p for p in params) or 'void'))
emit('static const struct eagl_gl_entry {\n\tconst char *name;\n\tvoid **pointer;\n} eagl_gl_entries[] = {')
for name in sorted(needed):
    emit('\t{ "%s", (void **)&%s },' % (name, name))
emit('};')
emit('#endif')
emit('#ifdef EAGL_GEN_TABLE')
emit('/* `lookup` finds a function of the library by name (hook_gl_proc); eagl_lookup() (eagl_s8.c) also tries the name')
emit(' * without its OES/EXT/APPLE/ARB/IMG ending. Returns how many of the functions the library does not have. */')
emit('static unsigned\neagl_resolve_functions(void)\n{\n\tunsigned missing = 0;\n')
emit('\tfor (unsigned i = 0; i < sizeof(eagl_gl_entries) / sizeof(eagl_gl_entries[0]); i++) {')
emit('\t\t*eagl_gl_entries[i].pointer = eagl_lookup(eagl_gl_entries[i].name);')
emit('\t\tif (*eagl_gl_entries[i].pointer == NULL) {\n\t\t\tmissing++;\n\t\t\teagl_resolve_missing(eagl_gl_entries[i].name);\n\t\t}')
emit('\t}\n\treturn missing;\n}')
known = {}
for offset, name, kind, function in entries:
    known[offset] = name
    if kind == 'pass':
        ret, params = protos[name]
        args = ', '.join(p[1] for p in params)
        emit('static %s\nslot_%04x(void *context%s)\n{' % (ret, offset, ''.join(', %s %s' % p for p in params)))
        emit('\tEAGL_ENTER(context, %#x);' % offset)
        emit('\tif (%s == NULL) {' % function)
        if ret == 'void':
            emit('\t\t(void)eagl_missing(context, %#x);\n\t\treturn;' % offset)
        else:
            emit('\t\treturn (%s)(uintptr_t)eagl_missing(context, %#x);' % (ret, offset))
        emit('\t}')
        emit('\tif (eagl_tracing) {\n\t\teagl_trace("%s(%s)\\n"%s);' % (name, ', '.join(trace_format(p[0]) for p in params),
             ''.join(', ' + trace_value(p) for p in params)))
        vector = re.match(r'glUniform(Matrix)?([1-4])fv$', name)
        if vector:
            n = int(vector.group(2))
            emit('\t\teagl_trace_floats(value, count * %d);' % (n * n if vector.group(1) else n))
        emit('\t}')
        if ret == 'void':
            emit('\t%s(%s);\n\tEAGL_LEAVE(context, %#x);\n}' % (function, args, offset))
        else:
            emit('\t%s result = %s(%s);\n\tEAGL_LEAVE(context, %#x);\n\treturn result;\n}' % (ret, function, args, offset))
    elif kind == 'none':
        emit('static long slot_%04x(void *context) { return eagl_missing(context, %#x); }' % (offset, offset))
top = max(known) + 0x100
for offset in range(8, top, 8):
    if offset not in known:
        emit('static long slot_%04x(void *context) { return eagl_missing(context, %#x); }' % (offset, offset))
emit('#define EAGL_TABLE_SIZE %#x' % top)
emit('static const char *\neagl_slot_name(unsigned offset)\n{\n\tswitch (offset) {')
for offset in sorted(known):
    emit('\tcase %#x: return "%s";' % (offset, known[offset]))
emit('\tdefault: return "?";\n\t}\n}')
emit('/* 1: QuartzCore is seen to call this entry (the "*" of eagl_slots.txt of the S9+ port) */')
emit('static int\neagl_slot_expected(unsigned offset)\n{\n\tswitch (offset) {')
for offset, used, names in slots:
    if used:
        emit('\tcase %#x:' % offset)
emit('\t\treturn 1;\n\tdefault:\n\t\treturn 0;\n\t}\n}')
emit('static void\neagl_fill_table(void **table)\n{')
hand = {offset: function for offset, name, kind, function in entries if kind == 'hand'}
for offset in range(8, top, 8):
    emit('\ttable[%#x / 8] = (void *)%s;' % (offset, hand.get(offset, 'slot_%04x' % offset)))
emit('}')
emit('#endif')
print('\n'.join(out))
passed = sum(1 for e in entries if e[2] == 'pass')
missing = [e[1] for e in entries if e[2] == 'none']
used_missing = [e[1] for (offset, used, names), e in zip(slots, entries) if used and e[2] == 'none']
print('mkeagl_s8.py: %d entries: %d passed on, %d by hand, %d without a function in gl.xml%s' % (
    len(entries), passed, len(hand), len(missing),
    '; of those QuartzCore calls: ' + ' '.join(used_missing) if used_missing else ''), file=sys.stderr)
